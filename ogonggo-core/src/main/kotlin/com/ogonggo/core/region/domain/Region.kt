/**
 * 채용공고의 시·도다.
 *
 * 값과 이름은 고용24 공통코드(지역코드)의 시·도를 따르며, 광주와 전남은 행정구역 통합에 맞춰 [JEONNAM_GWANGJU] 하나다.
 * [administrativeCode]는 행정구역 코드의 앞 두 자리다. 행정구역이 아닌 [NATIONWIDE]와 [OVERSEAS]는 없다.
 */
