    DAEGU(6, "대구", "27"),
    JEONNAM_GWANGJU(7, "전남광주", "12"),
    DAEJEON(8, "대전", "30"),
    ULSAN(9, "울산", "31"),
    SEJONG(10, "세종", "36"),
    GANGWON(11, "강원", "51"),
    GYEONGNAM(12, "경남", "48"),
    GYEONGBUK(13, "경북", "47"),
    CHUNGNAM(14, "충남", "44"),
    CHUNGBUK(15, "충북", "43"),
    JEONBUK(16, "전북", "52"),
    JEJU(17, "제주", "50"),
    OVERSEAS(18, "해외", null),
    ;

    companion object {
        /** 행정구역 코드 앞 두 자리로 시·도를 찾는다. 통합·개편 전 코드도 받는다. */
        fun fromAdministrativeCode(code: String): Region? {
            val prefix = AdministrativeCodes.normalize(code)?.take(2) ?: return null
            return entries.firstOrNull { it.administrativeCode == prefix }
        }
    }
}

