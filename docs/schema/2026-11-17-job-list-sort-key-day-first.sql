-- 공개 목록 최신순에서 등록일을 등록 경로보다 먼저 보도록 정렬 키의 자리를 바꾼다. 스키마는 바뀌지 않는다.
-- 예전: [크롤러·기업회원 여부 2^52][등록일 2^32~2^51][PICK 직군 2^31][무작위]
-- 지금: [등록일 2^33~2^52][크롤러·기업회원 여부 2^32][PICK 직군 2^31][무작위]
-- PICK 직군 비트와 무작위 값은 자리가 같아 아래 32비트를 그대로 둔다.
--
-- 예전 키만 고친다. 2^32로 나눈 몫이 예전 고용24 키는 등록일(epoch day, 2026년에 2만대),
-- 예전 크롤러·기업회원 키는 2^20 이상, 지금 키는 등록일의 두 배(2022년 이후면 38000 이상)라서 겹치지 않는다.
-- 그래서 배포 전후 어느 때 돌려도, 여러 번 돌려도 지금 키를 건드리지 않는다. 배포한 뒤 한 번 더 돌려 그 사이 예전 코드가 만든 키도 고친다.
-- 공고 분석이 수정 일시를 보므로 updated_at은 바꾸지 않는다.

update jobs
set list_sort_key = (((list_sort_key >> 32) & 1048575) << 33)
                  | (((list_sort_key >> 52) & 1) << 32)
                  | (list_sort_key & 4294967295)
where (list_sort_key >> 32) < 38000
   or (list_sort_key >> 32) >= 1048576;
